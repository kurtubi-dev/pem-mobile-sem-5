class Product {
  final String id;
  final String name;
  final String category;
  final double price;
  final int stock;
  final int discount;
  final String imageUrl;

  Product({
    required this.id,
    required this.name,
    required this.category,
    required this.price,
    required this.stock,
    required this.discount,
    required this.imageUrl,
  });
}
